import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTDIR = "E:/IDE1.0/.atlas-work/merge-test";
const FILE_URL = "file:///" + path.join(ROOT, "requirement-workbench.html").replace(/\\/g, "/");
const browser = await chromium.launch({ channel: "chrome" });
const page = await (await browser.newContext()).newPage();
await page.goto(FILE_URL, { waitUntil: "load" });
await page.waitForSelector("#reqList .g-req");
// 选一条需求 → 改意图/判据/状态 → 选变更类型 → 导出 JSON
await page.click('#reqList .g-req[data-req="FR-06"]');
await page.waitForTimeout(300);
await page.selectOption("#fType", "tighten");
await page.fill("#fIntent", "字符串搜索/置換：支持整词与大小写敏感，并给出命中数");
await page.fill("#fAcc", "前向/后向查找结果正确\n全量置換返回命中计数\n大小写敏感可配");
await page.fill("#fStatus", "✅ (工作台改)");
await page.fill("#fReason", "置換后需要给出命中数，便于验收");
await page.waitForTimeout(200);
await page.click('#tabs .g-tab[data-tab="set"]');
await page.waitForTimeout(300);
await page.click("#bExportJson");
await page.waitForTimeout(500);
const json = await page.$eval("#exportBox", (e) => e.textContent || "");
await browser.close();
fs.mkdirSync(OUTDIR, { recursive: true });
fs.writeFileSync(path.join(OUTDIR, "proposal.json"), json, "utf8");
console.log("提案已生成: " + json.length + " 字节 → " + path.join(OUTDIR, "proposal.json"));
